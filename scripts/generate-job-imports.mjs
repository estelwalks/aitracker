import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { tsImport } from "tsx/esm/api";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalogPath = join(
  root,
  "src/modules/tasks/definitions/job-catalog.json",
);
const outputPath = join(
  root,
  "src/modules/tasks/definitions/job-catalog.generated.ts",
);
const contract = await tsImport(
  join(root, "src/modules/tasks/definitions/contracts.ts"),
  import.meta.url,
);

const raw = JSON.parse(await readFile(catalogPath, "utf8"));
contract.assertSafeStaticCatalog(raw);
const catalog = contract.JobCatalogSchema.parse(raw);
const version = createHash("sha256")
  .update(JSON.stringify(catalog))
  .digest("hex")
  .slice(0, 16);
const body = `// @generated by scripts/generate-job-imports.mjs - DO NOT EDIT.\nimport type { JobCatalog, JobExecutorKey, JobTypeDefinition } from "./contracts.ts";\n\nexport const JOB_CATALOG: JobCatalog = ${JSON.stringify(catalog, null, 2)};\nexport const JOB_DEFINITIONS: readonly JobTypeDefinition[] = JOB_CATALOG.tasks;\nexport const JOB_EXECUTOR_KEYS: readonly JobExecutorKey[] = ${JSON.stringify([...new Set(catalog.tasks.map((task) => task.executorKey))])};\nexport const JOB_CATALOG_VERSION = ${JSON.stringify(version)};\n\n/** Explicit registry skeleton. P3-04 supplies implementations; no dynamic import is permitted. */\nexport const JOB_EXECUTOR_REGISTRY: Readonly<Record<JobExecutorKey, null>> = Object.freeze(Object.fromEntries(JOB_EXECUTOR_KEYS.map((key) => [key, null])) as Record<JobExecutorKey, null>);\n`;
await writeFile(outputPath, body, "utf8");
console.log(
  `generated ${relative(root, outputPath)} (${catalog.tasks.length} jobs, ${version})`,
);
