import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";
import { format } from "prettier";
import { tsImport } from "tsx/esm/api";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(root, "src/app/module-catalog.source.json");
const outputPath = join(root, "src/app/module-catalog.generated.ts");
// Windows: tsImport/ESM loaders reject bare drive-letter paths ("d:...");
// import specifiers must be file:// URLs.
const contract = await tsImport(
  pathToFileURL(join(root, "src/app/module-catalog.contracts.ts")).href,
  import.meta.url,
);
const catalog = JSON.parse(await readFile(sourcePath, "utf8"));

contract.assertSafeModuleCatalog(catalog);
const parsed = contract.ModuleCatalogSchema.parse(catalog);
const body = `// @generated by scripts/generate-module-catalog.mjs 鈥?DO NOT EDIT.

import type { PublicModuleCatalog } from "./module-catalog.contracts.ts";

export type { ModuleNavigationGroup, PublicModuleCatalog, PublicModuleCatalogEntry } from "./module-catalog.contracts.ts";

export const PUBLIC_MODULE_CATALOG: PublicModuleCatalog = ${JSON.stringify(parsed, null, 2)};

const FORBIDDEN_SERIALIZED_TOKENS = ["token", "secret", "password", "credential", "filesystem", "command", "pricing", "https://", "appdata", "library/", ".codex", ".claude"] as const;

export function moduleCatalogIsSafe(catalog: PublicModuleCatalog): boolean {
  const serialized = JSON.stringify(catalog).toLowerCase();
  return FORBIDDEN_SERIALIZED_TOKENS.every((token) => !serialized.includes(token));
}
`;
await writeFile(
  outputPath,
  await format(body, { parser: "typescript" }),
  "utf8",
);
console.log(`Wrote ${outputPath}`);
