import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { format } from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const sourcePath = join(root, "src/app/module-catalog.source.json");
const outputPath = join(root, "src/app/module-catalog.generated.ts");
const forbidden = [
  "token",
  "command",
  "apiKey",
  "password",
  "path",
  "AppData",
  "Library/",
  ".codex",
  ".claude",
];

const catalog = JSON.parse(await readFile(sourcePath, "utf8"));
const serialized = JSON.stringify(catalog).toLowerCase();
if (forbidden.some((token) => serialized.includes(token.toLowerCase()))) {
  throw new Error("Module catalog contains forbidden operational data.");
}

const body = `// @generated by scripts/generate-module-catalog.mjs — DO NOT EDIT.\n\nexport type ModuleNavigationGroup = "core" | "defense" | "infrastructure";\n\nexport interface PublicModuleCatalogEntry {\n  readonly id: string;\n  readonly navigation: { readonly group: ModuleNavigationGroup; readonly route: string };\n  readonly i18n: { readonly labelKey: string };\n  readonly capabilities: readonly string[];\n}\n\nexport interface PublicModuleCatalog {\n  readonly catalogVersion: 1;\n  readonly modules: readonly PublicModuleCatalogEntry[];\n}\n\nexport const PUBLIC_MODULE_CATALOG: PublicModuleCatalog = ${JSON.stringify(catalog, null, 2)};\n\nconst FORBIDDEN_SERIALIZED_TOKENS = ${JSON.stringify(forbidden)} as const;\n\nexport function moduleCatalogIsSafe(catalog: PublicModuleCatalog): boolean {\n  const serialized = JSON.stringify(catalog).toLowerCase();\n  return FORBIDDEN_SERIALIZED_TOKENS.every((token) => !serialized.includes(token.toLowerCase()));\n}\n`;
await writeFile(
  outputPath,
  await format(body, { parser: "typescript" }),
  "utf8",
);
console.log(`Wrote ${outputPath}`);
